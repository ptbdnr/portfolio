/**
 * Draws the map of Europe used by "Places that shaped me" from Natural Earth (public domain,
 * naturalearthdata.com): country outlines in a Mercator projection, simplified to SVG paths. Run
 * with `npm run map`; the output (src/content/europeMap.ts) is committed.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

type Position = [number, number]
type Geometry = { type: 'Polygon'; coordinates: Position[][] } | { type: 'MultiPolygon'; coordinates: Position[][][] }
type Feature = { properties: Record<string, unknown>; geometry: Geometry | null }

const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson'
const CACHE = path.resolve('node_modules/.cache/natural-earth/countries-50m.geojson')
const OUT = path.resolve('src/content/europeMap.ts')

/** The part of Europe shown, in degrees. */
export const BOUNDS = { west: -11, east: 31, south: 35.5, north: 60.5 }
export const WIDTH = 800
const TOLERANCE = 0.9
const HIGHLIGHT = ['HUN', 'ITA', 'DNK', 'NLD', 'GBR']

const mercY = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))
const SCALE = WIDTH / (((BOUNDS.east - BOUNDS.west) * Math.PI) / 180)
export const HEIGHT = Math.round((mercY(BOUNDS.north) - mercY(BOUNDS.south)) * SCALE)

export function project(lon: number, lat: number): [number, number] {
  return [((lon - BOUNDS.west) * Math.PI * SCALE) / 180, (mercY(BOUNDS.north) - mercY(lat)) * SCALE]
}

function simplify(points: [number, number][], tolerance: number): [number, number][] {
  if (points.length < 3) return points
  const keep = new Uint8Array(points.length)
  keep[0] = keep[points.length - 1] = 1
  const stack: [number, number][] = [[0, points.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()!
    const [ax, ay] = points[a]
    const [bx, by] = points[b]
    const len = Math.hypot(bx - ax, by - ay)
    let max = 0
    let index = -1
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i]
      // A closed ring starts and ends at the same point: measure from that point instead.
      const d = len < 1e-9 ? Math.hypot(px - ax, py - ay) : Math.abs((by - ay) * px - (bx - ax) * py + bx * ay - by * ax) / len
      if (d > max) {
        max = d
        index = i
      }
    }
    if (max > tolerance && index > 0) {
      keep[index] = 1
      stack.push([a, index], [index, b])
    }
  }
  return points.filter((_, i) => keep[i])
}

const clampTo = (v: number, max: number) => Math.min(max + 30, Math.max(-30, v))

function ringPath(ring: Position[]) {
  // Points far off the map are pulled to just outside its edge (out of sight), so long coastlines
  // elsewhere collapse into a few straight lines.
  const pts = simplify(
    ring.map(([lon, lat]) => {
      const [x, y] = project(lon, lat)
      return [clampTo(x, WIDTH), clampTo(y, HEIGHT)] as [number, number]
    }),
    TOLERANCE,
  )
  if (pts.length < 3) return ''
  const xs = pts.map((p) => p[0])
  const ys = pts.map((p) => p[1])
  // Skip shapes entirely outside the map.
  if (Math.max(...xs) <= -29 || Math.min(...xs) >= WIDTH + 29 || Math.max(...ys) <= -29 || Math.min(...ys) >= HEIGHT + 29) return ''
  return `M${pts.map(([x, y]) => `${Math.round(x)} ${Math.round(y)}`).join('L')}Z`
}

async function load(): Promise<Feature[]> {
  let text: string
  try {
    text = await readFile(CACHE, 'utf8')
  } catch {
    console.log(`downloading ${URL}`)
    const res = await fetch(URL)
    if (!res.ok) throw new Error(`download failed: ${res.status}`)
    text = await res.text()
    await mkdir(path.dirname(CACHE), { recursive: true })
    await writeFile(CACHE, text)
  }
  return (JSON.parse(text) as { features: Feature[] }).features
}

async function main() {
  const features = await load()
  let land = ''
  const countries: Record<string, string> = {}
  for (const f of features) {
    if (!f.geometry) continue
    const code = String(f.properties.ADM0_A3 ?? '')
    const polygons = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
    const d = polygons.map((rings) => ringPath(rings[0])).join('')
    if (!d) continue
    if (HIGHLIGHT.includes(code)) countries[code] = d
    else land += d
  }
  const source = `// Generated by scripts/build-map.ts from Natural Earth (public domain). Don't edit by hand.

export const MAP = {
  width: ${WIDTH},
  height: ${HEIGHT},
  bounds: ${JSON.stringify(BOUNDS)},
  /** Every other country. */
  land: ${JSON.stringify(land)},
  /** Countries I've lived in, by ISO code. */
  countries: ${JSON.stringify(countries, null, 2)} as Record<string, string>,
}

const mercY = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))
const SCALE = MAP.width / (((MAP.bounds.east - MAP.bounds.west) * Math.PI) / 180)

/** Where a place (longitude, latitude) is on the map, in its pixels. */
export function projectLonLat(lon: number, lat: number): [number, number] {
  return [((lon - MAP.bounds.west) * Math.PI * SCALE) / 180, (mercY(MAP.bounds.north) - mercY(lat)) * SCALE]
}
`
  await writeFile(OUT, source)
  console.log(`map: ${Math.round(source.length / 1024)} kB → ${path.relative(process.cwd(), OUT)}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) await main()
